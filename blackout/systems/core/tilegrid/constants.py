# ─── Chunk shape ─────────────────────────────────────────────────────────────

# Tiles along one side of a chunk. DESIGN-0011 decision: at least 64, like an
# OSRS map square.
CHUNK_SIZE: int = 64

# Corner heights along one side of a chunk. A tile has a height at each of its
# four corners, so a row of CHUNK_SIZE tiles has one more corner than tiles.
CORNERS_PER_SIDE: int = CHUNK_SIZE + 1

# The height of a new corner, in height steps.
DEFAULT_HEIGHT: int = 0

# The floor type index of a new tile. Index 0 of a chunk's floor names.
DEFAULT_FLOOR: int = 0

# ─── Walk flags ──────────────────────────────────────────────────────────────
# One int for each tile. A bit limits movement on the tile or across one edge.
# A wall sits on the edge of a tile. A step across an edge is refused if a wall
# is on either side of it, so an author can paint a wall on one tile only.

FLAG_NONE: int = 0
FLAG_BLOCKED: int = 1 << 0
FLAG_WATER: int = 1 << 1
FLAG_WALL_NORTH: int = 1 << 2
FLAG_WALL_EAST: int = 1 << 3
FLAG_WALL_SOUTH: int = 1 << 4
FLAG_WALL_WEST: int = 1 << 5

# A tile with any of these bits holds no player.
FLAGS_UNWALKABLE: int = FLAG_BLOCKED | FLAG_WATER

# The four wall bits. The path search reads them inline. A step that touches
# no wall and no unwalkable tile needs no call to `check_step`.
FLAGS_WALLS: int = (FLAG_WALL_NORTH | FLAG_WALL_EAST | FLAG_WALL_SOUTH
                    | FLAG_WALL_WEST)

# Every defined bit. A chunk file with a bit outside this mask is refused, so
# a typo in the editor cannot store a flag that no reader knows.
FLAGS_ALL: int = (FLAG_BLOCKED | FLAG_WATER | FLAG_WALL_NORTH | FLAG_WALL_EAST
                  | FLAG_WALL_SOUTH | FLAG_WALL_WEST)

# ─── Chunk file ──────────────────────────────────────────────────────────────
# DESIGN-0011 section 6.2. `chunkfile.py` reads and writes it in Python, and
# `godot/world/terrain/chunk_file.gd` in GDScript. Both readers read these
# values from one place: the GDScript copy is generated by
# `scripts/export_client_constants.py`.

# The newest format version. Format 2 adds the wall style layer (DESIGN-0013
# section 6.4). A reader accepts this format and CHUNK_FORMAT_PLAIN_WALLS, and
# refuses any other value.
CHUNK_FORMAT_VERSION: int = 2

# The format of a file whose every tile has DEFAULT_WALL_STYLE. It has no
# `wall_names` key and no `walls` key. The writer writes it for such a chunk.
# Thus, no file of format 1 needs a rewrite, and a diff shows only a real
# change.
CHUNK_FORMAT_PLAIN_WALLS: int = 1

# The wall style of each tile of a format 1 file. The first row of
# `world/wall_styles.py` has this key.
DEFAULT_WALL_STYLE: str = "plain"

# The highest plane. Plane 0 is the ground. OSRS has four planes, 0 to 3.
PLANE_MAX: int = 3

# The ground plane. Its rooms have the Z WORLD_Z, as before planes.
GROUND_PLANE: int = 0

# The room Z of a plane above the ground (Phase 7). `planes.plane_z` fills
# it. The pool of a plane adds POOL_Z_SUFFIX, which no plane Z matches.
PLANE_Z_TEMPLATE: str = "{world}_p{plane}"

# The range of a corner height, in height steps: a signed 16-bit int.
HEIGHT_MIN: int = -32768
HEIGHT_MAX: int = 32767

# An object turns in quarter turns, 0 to 3, as an OSRS object does.
ROTATION_COUNT: int = 4

# The tile step that the front of an object faces at each rotation: north,
# east, south, west. The turn is clockwise from above. A flight of stairs
# runs this way.
ROTATION_STEPS: tuple = ((0, 1), (1, 0), (0, -1), (-1, 0))

# The attribute that holds the rotation of the chunk object that stood an
# entity up. The tile sync writes it. The respawn queue keeps it. The
# statefeed sends it as the facing of the entity. At 0 the entity faces north.
FACING_ATTR: str = "facing"

# ─── The look of one object (10/16/2026) ─────────────────────────────────────
# A chunk object may carry a `look`: a variant, a scale, a tilt, and a nudge
# for that one placement. Nick chose it on 10/16/2026, so that fifty rusty
# poles are not fifty copies of one model. The server stores it and sends
# it, and never reads a value of it for a rule, as with the rotation. The
# attribute `LOOK_ATTR` holds it on the entity that the tile sync stood up,
# beside FACING_ATTR, and the respawn queue keeps it too.
#
# Every number is an int, so the two chunk file readers write the same
# bytes. The scale is in percent of the unit box. The tilt is in degrees on
# the three axes, over the quarter turn of the rotation. The nudge is in
# hundredths of a tile: x east, y up, z north. A key at its default (a scale
# of LOOK_SCALE_UNIT, a tilt or a nudge of zeros) is refused, so each look
# has one text. An object with no look writes the same bytes as before.
OBJECT_LOOK_KEY: str = "look"
LOOK_VARIANT_KEY: str = "variant"
LOOK_SCALE_KEY: str = "scale"
LOOK_TURN_KEY: str = "turn"
LOOK_OFFSET_KEY: str = "offset"
LOOK_KEYS: tuple = (LOOK_VARIANT_KEY, LOOK_SCALE_KEY, LOOK_TURN_KEY,
                    LOOK_OFFSET_KEY)

# The variant that lets the client pick: a hash of the tile picks the base
# model or one of its variants. Not a name, so no model record can take it.
# An object with no variant draws the base model.
LOOK_VARIANT_ANY: str = "*"

LOOK_SCALE_UNIT: int = 100
LOOK_SCALE_MIN: int = 10
LOOK_SCALE_MAX: int = 1000
LOOK_TURN_MAX: int = 180
LOOK_OFFSET_UNIT: int = 100
LOOK_OFFSET_MAX: int = 100
LOOK_AXES: int = 3

LOOK_ATTR: str = "look"

# ─── The spawn of one object (10/21/2026) ────────────────────────────────────
# An item spawn object carries a `spawn`: the item that lies on its tile, the
# quantity of it, and the ticks until a new one comes after the item leaves
# the tile. Nick chose four rules on 10/21/2026:
#
# 1. The spawn is a fact of each placement, as the words of a sign are.
# 2. The respawn is a count of game ticks, as OSRS gives a ground spawn.
# 3. The clock starts when the item leaves its tile.
# 4. Each new item rolls its quantity in the range of the spawn.
#
# The item is an ItemDef key. The quantity is [low, high], with
# SPAWN_QUANTITY_UNIT <= low <= high <= SPAWN_QUANTITY_MAX. A range of one
# unit is the default, and the reader refuses it, so each spawn has one text.
# The respawn is in SPAWN_RESPAWN_MIN..SPAWN_RESPAWN_MAX ticks. The item and
# the respawn are required. Every number is an int, as in a look.
OBJECT_SPAWN_KEY: str = "spawn"
SPAWN_ITEM_KEY: str = "item"
SPAWN_QUANTITY_KEY: str = "quantity"
SPAWN_RESPAWN_KEY: str = "respawn"
SPAWN_KEYS: tuple = (SPAWN_ITEM_KEY, SPAWN_QUANTITY_KEY, SPAWN_RESPAWN_KEY)
SPAWN_REQUIRED_KEYS: tuple = (SPAWN_ITEM_KEY, SPAWN_RESPAWN_KEY)

SPAWN_QUANTITY_UNIT: int = 1
SPAWN_QUANTITY_MAX: int = 100000

# The two numbers of a quantity: the low end and the high end.
SPAWN_QUANTITY_BOUNDS: int = 2
SPAWN_RESPAWN_MIN: int = 1

# One day of ticks, at 0.6 seconds for each tick.
SPAWN_RESPAWN_MAX: int = 144000

# The attribute on an item that an item spawn put down. It holds the item key
# of the spawn. `TileRoom.at_object_leave` reads it, and the clock of the
# spawn starts when the item leaves (`systems/gameplay/spawning/item_spawns.py`).
SPAWN_ITEM_ATTR: str = "spawn_item"

# A floor name, an area name, and an object kind. Lower case, digits, and
# underscores. Thus, no name needs a JSON escape, and the two writers cannot
# escape a name differently.
CHUNK_NAME_PATTERN: str = "^[a-z0-9_]+$"

# The words of an object that carries text: a signpost (Nick, 09/27/2026).
# One line of printable ASCII, with no space at either end. The pattern
# refuses `"` and `\`, so no text needs a JSON escape, as for a name. It
# refuses `|`, the start of an Evennia colour code, because a label strips
# markup and the chunk file must hold what a player reads.
CHUNK_TEXT_PATTERN: str = r"^[!#-\[\]-{}~]([ !#-\[\]-{}~]*[!#-\[\]-{}~])?$"

# The most characters in the text of one object. Not more than
# WORLD_LABEL_MAX_CHARS of the statefeed, so the label cap never cuts a sign
# that the chunk file holds. A test holds the two in that order.
CHUNK_TEXT_MAX_CHARS: int = 64

# The file name of a chunk file, and the directory of the world, from the
# game directory.
CHUNK_FILE_TEMPLATE: str = "chunk_{cx}_{cy}_p{plane}.json"
CHUNK_DIRECTORY: str = "world/chunks"

# The templates of the Build tab (DESIGN-0013 section 6.6), from the game
# directory. One file holds one template, named `<key>.json`. The server never
# loads a template. The terrain editor writes it, and
# `world/tests/test_structure_templates.py` checks its names.
STRUCTURE_DIRECTORY: str = "world/structures"
STRUCTURE_FILE_SUFFIX: str = ".json"
STRUCTURE_FORMAT_VERSION: int = 1

# The table files, from the game directory (10/14/2026). One file holds the
# rows of one table: `areas.json`, `floor_types.json`, `wall_styles.json`,
# and `decor_kinds.json`. `world/table_file.py` reads them, and the Tables
